/** English Metric Units: 914400 per inch, 360000 per centimetre. The base length unit across DrawingML. */
export type Emu = number;

/** 60,000ths of a degree, used for rotation and angle attributes. */
export type Angle = number;

/** 1000ths of a percent, e.g. 100000 represents 100%. */
export type Percentage = number;

/** Hundredths of a point, e.g. 1800 represents 18pt. */
export type FontSize = number;
